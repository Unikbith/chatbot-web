DEFAULT_PROTOCOL = 'full'
# 默认长文：每轮要填状态条 / 三块角色面板 / 全部数值 / 内心 / 推演，短文装不下这些内容
DEFAULT_LENGTH = 'long'


def compose_reply_spec(protocol=DEFAULT_PROTOCOL, length=DEFAULT_LENGTH, enhance=True):
    """组合要注入系统提示词的完整规范。

    enhance=False（用户关掉「提示词增强」）时只给标记词表，
    不强制每轮输出结构 —— 保留"按需使用标记"的自由度。
    """
    if not enhance:
        return MARKER_VOCAB
    return MARKER_VOCAB + STRUCTURE_SPEC + LENGTH_PROMPTS.get(length, LENGTH_PROMPTS[DEFAULT_LENGTH])
