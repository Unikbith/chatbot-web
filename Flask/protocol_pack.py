def _trim(text, limit):
    text = (text or '').strip()
    return text[:limit] if len(text) > limit else text

def protocol_entries():
    """返回要种入每张人物卡的协议条目定义（供幂等种入使用）。

    每条都自带 source_key：同 key 视为同一条，重复种入只会更新内容，不会产生副本。
    """
    # 结构协议 = 标记词表 + 每轮输出结构（**不含篇幅档**）：
    # 篇幅是会话级设置，由 _protocol_block 按当前档位动态追加；
    # 早先把 default 档写进条目正文，会出现「条目里写着适中、会话设置是长文」以及
    # 同一行篇幅要求重复出现两次的问题。
    structure = (reply_spec.MARKER_VOCAB + reply_spec.STRUCTURE_SPEC).strip()
    entries = [
        {
            'source_key': 'protocol:structure',
            'title': '① 输出结构协议（由「界面标记 → 丰富面板内容」控制）',
            'kind': 'structure',
            'gate': 'enhance',
            'always_on': False,
            'keywords': '',
            'weight': 100,
            'content': structure,
        },
        {
            'source_key': 'protocol:content',
            'title': '② 创作与内容协议（由「对话设置 → 提示词兜底」控制）',
            'kind': 'content',
            'gate': 'append',
            'always_on': False,   # 不再常驻：默认关闭，由会话开关决定是否注入
            'keywords': '',
            'weight': 90,
            'content': _content_protocol(),
        },
        {
            'source_key': 'protocol:experience',
            'title': '③ 剧情推进与体验协议（由「对话设置 → 提示词兜底」控制）',
            'kind': 'experience',
            'gate': 'append',
            'always_on': False,   # 同上
            'keywords': '',
            'weight': 80,
            'content': _EXPERIENCE,
        },
    ]
    for pack in _PLAY_PACKS:
        entries.append({
            'source_key': pack['source_key'],
            'title': pack['title'],
            'kind': 'play',
            'gate': 'play',
            'always_on': False,          # 玩法包按需触发（关键词命中才注入）
            'keywords': pack['keywords'],
            'weight': 10,
            'content': pack['content'],
        })
    return [e for e in entries if (e['content'] or '').strip()]


def entry_content_of(source_key):
    """按 source_key 取条目正文（恢复默认时用）。"""
    for e in protocol_entries():
        if e['source_key'] == source_key:
            return e['content']
    return ''


def play_keywords(entry):
    """取一条玩法包条目的可用触发词：丢掉单字词（见 MIN_PLAY_KEYWORD_LEN 的说明）。

    用户自己新增玩法包时也可能写单字词，这里统一兜住，
    避免再出现「日常对话命中极端玩法」。
    """
    raw = (getattr(entry, 'keywords', '') or '')
    out = []
    for part in re.split(r'[,，;；\n\r]+', raw):
        kw = part.strip().lower()
        if len(kw) >= MIN_PLAY_KEYWORD_LEN:
            out.append(kw)
    return out
